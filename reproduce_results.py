#!/usr/bin/env python3
"""Recompute final-paper tables/statistics from packaged report snapshots.

Python standard library only; no training, model downloads, or inference.
Run: python reproduce_results.py [--output results/generated]
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import html
import json
import math
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE / 'results'
LABELS = {
    'full_oracle_rloo': 'Full-oracle RLOO', 'cheap_rloo': 'Cheap RLOO',
    'linear_replace': 'Direct replacement', 'linear_ipw': 'Linear IPW',
    'oracle_only': 'Sparse oracle-only', 'oracle_centered': 'Centered sparse oracle',
    'group_scaled_ipw': 'Group-scaled IPW',
    'full_oracle_group_scaled': 'Full-oracle group-scaled',
    'preaudit_scaled_ipw': 'Pre-audit-scaled IPW', 'cheap_grpo': 'Native cheap GRPO',
    'cheap_rloo_observer': 'Cheap RLOO, observer',
}
STEPS = (0, 20, 40, 80, 120)


def load(path):
    return json.loads(path.read_text())


def csv_file(out, name, fields, rows):
    with (out / (name + '.csv')).open('w', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(fields)
        writer.writerows(rows)


def percent(x):
    return f'{100 * x:.2f}'


def evaluations(run):
    return {e['step']: e for e in run['evaluations']}


def final(run):
    return evaluations(run)[run['final_step']]


def pair_cell(e):
    return f"{percent(e['accuracy'])} / {percent(e['fp_occupancy'])}"


def table_rows(text):
    # All five reference assets are simple tabulars; skip captions/headings.
    return [line.strip() for line in text.splitlines()
            if '&' in line and line.rstrip().endswith(r'\\')
            and not line.startswith(('Update &', 'Trusted labels /', 'Seed &'))]


def write_table(out, name, header, rows, alignment):
    lines = [' & '.join(map(str, r)) + r' \\' for r in rows]
    reference = table_rows((DATA / 'reference_tables' / (name + '.tex')).read_text())
    if lines != reference:
        raise AssertionError(f'{name}: final-paper table differs from regenerated data')
    text = '% Generated by reproduce_results.py from packaged report snapshots.\n'
    text += '\\begin{tabular}{' + alignment + '}\n\\toprule\n'
    text += ' & '.join(header) + ' \\\\\n\\midrule\n'
    text += '\n'.join(lines) + '\n\\bottomrule\n\\end{tabular}\n'
    (out / (name + '.tex')).write_text(text)
    csv_file(out, name, header, rows)
    return len(lines)


def run_id(method, seed, short=False):
    suffix = '01' if seed == 101 or short else 'long-01'
    return f"full-python-{method.replace('_', '-')}-s{seed}-{suffix}"


def svg_figure(out, runs):
    """Plot the same six series as Figure 1; geometry/font differ from paper PDF."""
    svg = ['<svg xmlns="http://www.w3.org/2000/svg" width="960" height="380" viewBox="0 0 960 380">',
           '<rect width="960" height="380" fill="white"/>',
           '<g font-family="sans-serif" font-size="13" fill="#222">']
    styles = [('linear_ipw', '#0072B2', ''), ('oracle_only', '#009E73', '7 4'),
              ('group_scaled_ipw', '#D55E00', '2 4')]
    for panel, seed in enumerate((202, 303)):
        left, top, width, height = 65 + panel * 465, 42, 390, 245
        px = lambda step: left + width * step / 120
        py = lambda accuracy: top + height * (1 - accuracy / 85)
        svg.append(f'<text x="{left + width / 2}" y="24" text-anchor="middle">Continuation seed {seed}</text>')
        for value in [0, 20, 40, 60, 80]:
            y = py(value)
            svg += [f'<path d="M {left} {y} H {left + width}" stroke="#ddd"/>',
                    f'<text x="{left - 8}" y="{y + 4}" text-anchor="end">{value}</text>']
        for step in [0, 40, 80, 120]:
            svg.append(f'<text x="{px(step)}" y="{top + height + 20}" text-anchor="middle">{step}</text>')
        svg.append(f'<path d="M {left} {top} V {top + height} H {left + width}" fill="none" stroke="#222"/>')
        for method, color, dash in styles:
            ev = runs[run_id(method, seed)]['evaluations']
            points = ' '.join(f"{px(e['step']):.3f},{py(100 * e['accuracy']):.3f}" for e in ev)
            svg.append(f'<polyline points="{points}" fill="none" stroke="{color}" stroke-width="2.3" stroke-dasharray="{dash}"/>')
            for e in ev:
                svg.append(f'<circle cx="{px(e["step"]):.3f}" cy="{py(100 * e["accuracy"]):.3f}" r="3" fill="{color}"/>')
        svg.append(f'<text x="{left + width / 2}" y="332" text-anchor="middle">Policy updates</text>')
    svg.append('<text x="18" y="165" transform="rotate(-90 18 165)" text-anchor="middle">Held-out accuracy (%)</text>')
    for index, (method, color, dash) in enumerate(styles):
        x = 175 + index * 250
        svg += [f'<path d="M {x} 361 h 28" stroke="{color}" stroke-width="2.3" stroke-dasharray="{dash}"/>',
                f'<text x="{x + 36}" y="365">{html.escape(LABELS[method])}</text>']
    svg.append('</g></svg>')
    (out / 'long_accuracy.svg').write_text('\n'.join(svg) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=DATA / 'generated')
    out = parser.parse_args().output
    out.mkdir(parents=True, exist_ok=True)
    manifest = load(DATA / 'SOURCE_MANIFEST.json')
    for entry in manifest['files']:
        actual = hashlib.sha256((HERE / entry['file']).read_bytes()).hexdigest()
        if actual != entry['sha256']:
            raise AssertionError('Packaged source checksum mismatch: ' + entry['file'])

    runs, dense = {}, []
    for path in sorted((DATA / 'reports').glob('*/summary.json')):
        report = load(path)
        for original in report['runs']:
            run = dict(original)
            if 'proposal' in run:
                run.update(train_run=Path(run['run']).name, method='cheap_rloo_observer',
                           final_step=run['planned_steps'], evaluations=run['heldout']['evaluations'],
                           learner_oracle_calls=0, evaluator_oracle_calls=run['heldout']['evaluator_oracle_calls'],
                           training_rollouts=run['planned_steps'] * 256)
            run['source_report'] = report['source_report']
            if 'dense' in path.parent.name:
                dense.append(run)
                continue
            if run['train_run'] in runs:
                raise AssertionError('Duplicate selected run: ' + run['train_run'])
            runs[run['train_run']] = run
            for e in run['evaluations']:
                for metric, vector in [('accuracy', 'prompt_values'), ('fp_occupancy', 'prompt_fp')]:
                    if vector in e:
                        assert len(e[vector]) == 128
                        assert abs(statistics.mean(e[vector]) - e[metric]) < 1e-12

    def get(method, seed, short=False):
        return runs[run_id(method, seed, short)]

    order = [get(m, 101)['train_run'] for m in
             ['oracle_rloo', 'cheap_rloo', 'linear_replace', 'linear_ipw', 'oracle_only', 'oracle_centered']]
    for seed in (202, 303):
        if seed == 202:
            order.append(get('cheap_rloo', seed, True)['train_run'])
        order.append(f'full-update-observer-cheap-rloo-s{seed}-20260911-01')
        order += [get(m, seed)['train_run'] for m in
                  (['linear_ipw', 'oracle_only', 'group_scaled_ipw'] if seed == 202 else
                   ['linear_ipw', 'oracle_only', 'oracle_centered', 'group_scaled_ipw'])]
        order += [f'full-python-cheap-grpo-s{seed}-long-01', f'full-python-cheap-grpo-s{seed}-40-01',
                  get('preaudit_scaled_ipw', seed)['train_run']]
        if seed == 303:
            order += [get(m, seed)['train_run'] for m in ['oracle_rloo', 'oracle_group_scaled']]
    assert set(order) == set(runs) and len(order) == 24

    traj_rows, flat_rows, endpoint_rows = [], [], []
    for rid in order:
        run = runs[rid]
        label = LABELS[run['method']]
        if 'cheap-grpo' in rid and '-40-' in rid:
            label += ' (40)'
        added = run['method'] in ['cheap_rloo_observer', 'preaudit_scaled_ipw', 'cheap_grpo'] or (run['method'] == 'cheap_rloo' and run['seed'] == 202)
        table_label = label + (r'$^\dagger$' if added else '')
        ev = evaluations(run)
        traj_rows.append([str(run['seed']), table_label, *[pair_cell(ev[s]) if s in ev else '' for s in STEPS]])
        for step, e in ev.items():
            flat_rows.append([rid, run['seed'], label, step, 100 * e['accuracy'], 100 * e['fp_occupancy'], run['source_report']])
        endpoint_rows.append([rid, run['seed'], label, run['final_step'], 100 * final(run)['accuracy'],
                              100 * final(run)['fp_occupancy'], run['learner_oracle_calls'],
                              run['training_rollouts'], run['evaluator_oracle_calls'], run.get('observer_labels', 0),
                              run['training_rollouts'], run['source_report']])
    fields = ['run_id', 'seed', 'method', 'step', 'accuracy_percent', 'wrong_trigger_share_percent', 'source_report']
    csv_file(out, 'trajectories', fields, flat_rows)
    csv_file(out, 'endpoints_and_labels', ['run_id', 'seed', 'method', 'final_step', 'accuracy_percent',
             'wrong_trigger_share_percent', 'policy_labels', 'training_responses', 'evaluation_labels',
             'shadow_predictor_labels', 'diagnostic_training_labels', 'source_report'], endpoint_rows)
    counts = {}
    counts['traj_results'] = write_table(out, 'traj_results', ['Seed', 'Method', *map(str, STEPS)], traj_rows, 'rlccccc')
    short_rows = [[LABELS[runs[rid]['method']], f"{runs[rid]['learner_oracle_calls']:,}",
                   percent(final(runs[rid])['accuracy']), percent(final(runs[rid])['fp_occupancy'])] for rid in order[:6]]
    counts['short_results'] = write_table(out, 'short_results', ['Update', 'Trusted labels', r'Accuracy (\%)', r'Wrong-trigger share (\%)'], short_rows, 'lrrr')
    density = [[budget, pair_cell(final(get(left, 303))), pair_cell(final(get(right, 303)))]
               for budget, left, right in [('307 / 30,720', 'linear_ipw', 'group_scaled_ipw'),
                                          ('30,720 / 30,720', 'oracle_rloo', 'oracle_group_scaled')]]
    counts['density_scaling'] = write_table(out, 'density_scaling', ['Trusted labels / rollouts', 'Linear', 'Group-scaled'], density, 'lrr')
    preaudit = [[str(seed), *[pair_cell(final(get(method, seed))) for method in ['linear_ipw', 'group_scaled_ipw', 'preaudit_scaled_ipw']]] for seed in (303, 202)]
    counts['preaudit_results'] = write_table(out, 'preaudit_results', ['Seed', 'Linear IPW', 'Group-scaled IPW', 'Pre-audit-scaled IPW'], preaudit, 'rrrr')

    # The paper ledger omits observer timing; preserve its row order exactly.
    cost_order = [get(m, 101)['train_run'] for m in ['oracle_rloo', 'cheap_rloo', 'linear_ipw', 'oracle_only', 'oracle_centered', 'linear_replace']]
    cost_order += [get(m, 202)['train_run'] for m in ['linear_ipw', 'oracle_only', 'group_scaled_ipw']]
    cost_order += [get(m, 303)['train_run'] for m in ['linear_ipw', 'oracle_only', 'oracle_centered', 'group_scaled_ipw', 'oracle_rloo', 'oracle_group_scaled']]
    cost_order += [get('preaudit_scaled_ipw', s)['train_run'] for s in (303, 202)]
    cost_order += [get('cheap_rloo', 202, True)['train_run']]
    cost_order += [f'full-python-cheap-grpo-s{s}-{h}-01' for s in (202, 303) for h in ('long', '40')]
    cost_rows = []
    for rid in cost_order:
        r = runs[rid]
        cost_rows.append([str(r['seed']), str(r['final_step']), LABELS[r['method']], f"{r['learner_oracle_calls']:,}",
                          f"{r['generated_response_tokens_from_lengths']/1e6:.2f}", f"{r['trainer_num_input_tokens_seen']/1e6:.2f}",
                          f"{r['training_seconds']/3600:.2f}"])
    counts['costs_cr'] = write_table(out, 'costs_cr', ['Seed', 'Steps', 'Method', 'Labels', 'Resp. M', 'Train M', 'Hours'], cost_rows, 'rrlrrrr')
    csv_file(out, 'costs_exact', ['run_id', 'response_tokens', 'trainer_input_tokens', 'training_seconds'],
             [[rid, runs[rid]['generated_response_tokens_from_lengths'], runs[rid]['trainer_num_input_tokens_seen'], runs[rid]['training_seconds']] for rid in cost_order])

    comparisons = []
    def contrast(name, seed, terms, expected):
        vectors = [(weight, final(get(method, seed))['prompt_values']) for method, weight in terms]
        diffs = [sum(weight * v[i] for weight, v in vectors) for i in range(128)]
        mean = 100 * statistics.mean(diffs)
        se = 100 * statistics.stdev(diffs) / math.sqrt(len(diffs))
        assert (f'{mean:.2f}', f'{se:.2f}') == expected, (name, mean, se)
        comparisons.append([name, seed, 128, mean, se, ' + '.join(f'{w}*{m}' for m, w in terms)])
    contrast('linear_minus_oracle_only', 202, [('linear_ipw', 1), ('oracle_only', -1)], ('12.11', '3.75'))
    contrast('linear_minus_oracle_only', 303, [('linear_ipw', 1), ('oracle_only', -1)], ('19.92', '3.57'))
    contrast('linear_minus_centered_oracle', 303, [('linear_ipw', 1), ('oracle_centered', -1)], ('12.50', '3.72'))
    contrast('sparse_minus_dense_scaling_effect', 303, [('linear_ipw', 1), ('group_scaled_ipw', -1), ('oracle_rloo', -1), ('oracle_group_scaled', 1)], ('67.19', '4.97'))
    for seed, expected in [(303, ('31.25', '3.14')), (202, ('46.88', '3.63'))]:
        contrast('preaudit_minus_group_scaled', seed, [('preaudit_scaled_ipw', 1), ('group_scaled_ipw', -1)], expected)
    for seed, expected in [(303, ('32.42', '3.70')), (202, ('28.12', '3.36'))]:
        contrast('linear_minus_preaudit', seed, [('linear_ipw', 1), ('preaudit_scaled_ipw', -1)], expected)
    csv_file(out, 'paired_question_comparisons', ['contrast', 'seed', 'question_count', 'difference_pp', 'paired_question_se_pp', 'terms'], comparisons)
    dense_rows = [[r['train_run'], r['seed'], LABELS[r['method']], e['step'], 100*e['accuracy'], 100*e['fp_occupancy'], r['source_report']] for r in dense for e in r['evaluations']]
    csv_file(out, 'denser_evaluation', fields, dense_rows)
    de = evaluations(dense[0])
    assert pair_cell(de[60]) == '49.22 / 22.66' and pair_cell(de[100]) == '64.45 / 5.47'
    assert dense[0]['evaluator_oracle_calls'] == 2048

    diagnostic_rows, diagnostic_summary = [], {}
    for path in sorted((DATA / 'diagnostics').glob('*.json')):
        d = load(path)
        rows = d['records']
        for row in rows:
            fp = sum(c > y for c, y in zip(row['audited_cheap_rewards'], row['bought_labels']))
            row['audited_false_positives'] = fp
            diagnostic_rows.append([d['run_id'], row['step'], len(row['bought_labels']), fp, row['grad_norm']])
        diag = {'audits': sum(len(r['bought_labels']) for r in rows), 'audited_false_positives': sum(r['audited_false_positives'] for r in rows)}
        if 'linear-ipw' in d['run_id']:
            diag['windows_inclusive'] = {f'{a}-{b}': sum(r['audited_false_positives'] for r in rows if a <= r['step'] <= b) for a, b in [(20, 30), (31, 40), (41, 50), (91, 101)]}
            diag['steps_with_audited_fp'] = sum(r['audited_false_positives'] > 0 for r in rows)
            diag['fp_steps_grad_norm_above_one'] = sum(r['audited_false_positives'] > 0 and r['grad_norm'] > 1 for r in rows)
            diag['no_fp_steps_grad_norm_above_one'] = sum(r['audited_false_positives'] == 0 and r['grad_norm'] > 1 for r in rows)
            assert diag == {'audits':307, 'audited_false_positives':45, 'windows_inclusive':{'20-30':0,'31-40':10,'41-50':12,'91-101':0}, 'steps_with_audited_fp':36, 'fp_steps_grad_norm_above_one':34, 'no_fp_steps_grad_norm_above_one':0}
        else:
            assert diag == {'audits':307,'audited_false_positives':275}
        diagnostic_summary[d['run_id']] = diag
    csv_file(out, 'seed303_audit_diagnostics', ['run_id','step','audits','audited_false_positives','recorded_grad_norm'], diagnostic_rows)
    (out / 'seed303_audit_summary.json').write_text(json.dumps(diagnostic_summary, indent=2)+'\n')

    figure_rows = [row for row in flat_rows if row[0] in {run_id(m,s) for s in (202,303) for m in ['linear_ipw','oracle_only','group_scaled_ipw']}]
    csv_file(out, 'long_accuracy', fields, figure_rows)
    svg_figure(out, runs)
    verification = {'status':'passed', 'scope':'Recompute statistics and plotted data from selected archived summaries; no training or inference.',
                    'source_files_sha256_verified':len(manifest['files']), 'unique_paper_runs':len(runs),
                    'checkpoint_rows':len(flat_rows), 'exact_final_paper_table_rows_verified':counts,
                    'main_text_paired_question_contrasts_verified':len(comparisons),
                    'seed303_diagnostic_rows':len(diagnostic_rows),
                    'figure':'long_accuracy.svg has the same six data series as the paper, with independent SVG styling.',
                    'uncertainty':'Question-paired SE; policies held fixed; seeds analyzed separately.',
                    'limitations':['Saved summary means are the input; this script does not regrade raw responses.',
                                   'Observer summaries supply aggregate trajectories, not question vectors.',
                                   'Starting model weights and historical upstream model revision are not packaged.']}
    (out/'verification.json').write_text(json.dumps(verification,indent=2)+'\n')
    print(json.dumps(verification,indent=2))


if __name__ == '__main__':
    main()
